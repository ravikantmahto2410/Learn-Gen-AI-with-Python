##### Lets understand about the indexing

mycar = 'Tata Harrier'
print(f'My Favorite car first Word : {mycar[0:4]}')
print(f'My Favorite car first Word : {mycar[0:3]}')
print(f'My Favorite car first Word : {mycar[0:4:1]}')
print(f'My Favorite car first Word : {mycar[0:4:2]}')
print(f'My Favorite car first word : {mycar[:4]}')
print(f'My Favorite car last word : {mycar[4:]}')
print(f'My favorite car reversed words : {mycar[::-1]}')
